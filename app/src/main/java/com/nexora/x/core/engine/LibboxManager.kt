package com.nexora.x.core.engine

import android.content.Context
import dagger.hilt.android.qualifiers.ApplicationContext
import java.io.File
import java.lang.reflect.InvocationHandler
import java.lang.reflect.Proxy
import java.util.concurrent.atomic.AtomicBoolean
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Callback interface bridging `libbox` (`io.nekohasekai.libbox.PlatformInterface`) TUN and socket
 * operations to Android's [com.nexora.x.core.engine.service.NexoraVpnService].
 */
interface NexoraTunPlatformCallbacks {
    /**
     * Protects an outbound socket file descriptor from routing loops via `VpnService.protect(fd)`.
     */
    fun protectSocketFd(fd: Int): Boolean

    /**
     * Establishes the Android `VpnService.Builder` TUN interface using parameters from `TunOptions`
     * and returns the detached native file descriptor (`ParcelFileDescriptor.detachFd()`).
     */
    @Throws(Exception::class)
    fun openTunInterface(
        mtu: Int,
        ipv4Address: String,
        ipv4Prefix: Int,
        dnsAddress: String
    ): Int

    /**
     * Receives log lines emitted by the native sing-box core.
     */
    fun onNativeCoreLog(message: String)

    /**
     * Receives real-time traffic statistics from `libbox` `CommandClientHandler.writeStatus`.
     */
    fun onTrafficStatusUpdate(stats: EngineTrafficStatistics)
}

/**
 * Manages initialization, config validation, and service lifecycle for the official
 * `sing-box` Android library (`io.nekohasekai.libbox` from `app/libs/libbox.aar`, pinned to v1.10.7).
 *
 * Truthfulness & Binary Verification:
 * - Inspects the runtime classpath for `io.nekohasekai.libbox.Libbox` (generated by `gomobile bind`).
 * - If `app/libs/libbox.aar` is packaged, invokes the real `Libbox.setup(SetupOptions)`,
 *   `Libbox.version()`, `Libbox.checkConfig(String)`, and `Libbox.newService(String, PlatformInterface)`.
 * - If `libbox.aar` has not yet been placed in `app/libs/`, [isNativeLibboxLoaded] returns `false`
 *   and any attempt to start the tunnel throws [EngineException.LibboxBinaryUnavailableException]
 *   rather than faking a VPN connection.
 */
@Singleton
class LibboxManager @Inject constructor(
    @ApplicationContext private val context: Context
) {
    companion object {
        const val PINNED_SINGBOX_VERSION = "1.10.7"
        const val LIBBOX_PACKAGE = "io.nekohasekai.libbox"
        const val LIBBOX_MAIN_CLASS = "$LIBBOX_PACKAGE.Libbox"
        const val SETUP_OPTIONS_CLASS = "$LIBBOX_PACKAGE.SetupOptions"
        const val PLATFORM_INTERFACE_CLASS = "$LIBBOX_PACKAGE.PlatformInterface"
    }

    private val initialized = AtomicBoolean(false)

    @Volatile
    private var activeBoxServiceInstance: Any? = null

    /**
     * Checks whether the `io.nekohasekai.libbox.Libbox` JNI class from `libbox.aar` is present.
     */
    fun isNativeLibboxLoaded(): Boolean {
        return try {
            Class.forName(LIBBOX_MAIN_CLASS)
            true
        } catch (_: Throwable) {
            false
        }
    }

    fun isInitialized(): Boolean = initialized.get()

    /**
     * Queries `Libbox.version()` when `libbox.aar` is present, or returns an honest status label.
     */
    fun queryEngineVersion(): String {
        if (!isNativeLibboxLoaded()) {
            return "sing-box $PINNED_SINGBOX_VERSION (libbox.aar missing in app/libs/)"
        }
        return try {
            val libboxClass = Class.forName(LIBBOX_MAIN_CLASS)
            val versionMethod = libboxClass.getMethod("version")
            val ver = versionMethod.invoke(null) as? String
            if (!ver.isNullOrBlank()) "sing-box $ver (libbox JNI)" else "sing-box $PINNED_SINGBOX_VERSION"
        } catch (_: Throwable) {
            "sing-box $PINNED_SINGBOX_VERSION (JNI)"
        }
    }

    /**
     * Initializes `io.nekohasekai.libbox.Libbox.setup(SetupOptions)` with the app's private
     * base, working, and temp directories.
     */
    @Throws(EngineException::class)
    fun ensureInitialized() {
        if (initialized.get()) return
        if (!isNativeLibboxLoaded()) {
            throw EngineException.LibboxBinaryUnavailableException(
                "Cannot initialize sing-box: io.nekohasekai.libbox.Libbox (libbox.aar v$PINNED_SINGBOX_VERSION) is not present in app/libs/."
            )
        }

        try {
            val baseDir = File(context.filesDir, "singbox").apply { mkdirs() }
            val workDir = File(context.getExternalFilesDir(null) ?: context.filesDir, "singbox_work").apply { mkdirs() }
            val tempDir = File(context.cacheDir, "singbox_tmp").apply { mkdirs() }

            val setupOptionsClass = Class.forName(SETUP_OPTIONS_CLASS)
            val setupOptions = setupOptionsClass.getDeclaredConstructor().newInstance()

            runCatching {
                setupOptionsClass.getMethod("setBasePath", String::class.java)
                    .invoke(setupOptions, baseDir.absolutePath)
            }
            runCatching {
                setupOptionsClass.getMethod("setWorkingPath", String::class.java)
                    .invoke(setupOptions, workDir.absolutePath)
            }
            runCatching {
                setupOptionsClass.getMethod("setTempPath", String::class.java)
                    .invoke(setupOptions, tempDir.absolutePath)
            }
            runCatching {
                setupOptionsClass.getMethod("setFixAndroidStack", Boolean::class.javaPrimitiveType)
                    .invoke(setupOptions, true)
            }

            val libboxClass = Class.forName(LIBBOX_MAIN_CLASS)
            val setupMethod = libboxClass.getMethod("setup", setupOptionsClass)
            setupMethod.invoke(null, setupOptions)
            initialized.set(true)
        } catch (e: Throwable) {
            val unwrapped = e.cause ?: e
            throw EngineException.EngineInitializationException(
                "Libbox.setup failed: ${unwrapped.message ?: unwrapped.javaClass.simpleName}",
                unwrapped
            )
        }
    }

    /**
     * Invokes `Libbox.checkConfig(configJson)` when `libbox.aar` is loaded.
     */
    @Throws(EngineException.InvalidConfigurationException::class)
    fun checkConfigWithNativeLibboxIfAvailable(configJson: String) {
        if (!isNativeLibboxLoaded()) return
        try {
            val libboxClass = Class.forName(LIBBOX_MAIN_CLASS)
            val checkMethod = libboxClass.getMethod("checkConfig", String::class.java)
            checkMethod.invoke(null, configJson)
        } catch (e: Throwable) {
            val cause = e.cause ?: e
            throw EngineException.InvalidConfigurationException(
                "libbox checkConfig rejected configuration: ${cause.message ?: "syntax error"}"
            )
        }
    }

    /**
     * Instantiates and starts `io.nekohasekai.libbox.BoxService` via `Libbox.newService(configJson, platformInterface)`.
     */
    @Synchronized
    @Throws(EngineException::class)
    fun startNativeBoxService(
        configJson: String,
        callbacks: NexoraTunPlatformCallbacks
    ) {
        ensureInitialized()
        checkConfigWithNativeLibboxIfAvailable(configJson)

        try {
            val libboxClass = Class.forName(LIBBOX_MAIN_CLASS)
            val platformInterfaceClass = Class.forName(PLATFORM_INTERFACE_CLASS)

            val platformProxy = Proxy.newProxyInstance(
                platformInterfaceClass.classLoader,
                arrayOf(platformInterfaceClass),
                createPlatformInvocationHandler(callbacks)
            )

            val newServiceMethod = libboxClass.getMethod(
                "newService",
                String::class.java,
                platformInterfaceClass
            )
            val boxService = newServiceMethod.invoke(null, configJson, platformProxy)
                ?: throw EngineException.RuntimeExecutionException("Libbox.newService returned null.")

            val startMethod = boxService.javaClass.getMethod("start")
            startMethod.invoke(boxService)

            activeBoxServiceInstance = boxService
        } catch (e: EngineException) {
            throw e
        } catch (e: Throwable) {
            val cause = e.cause ?: e
            throw EngineException.RuntimeExecutionException(
                "Failed to start libbox BoxService: ${cause.message ?: cause.javaClass.simpleName}",
                cause
            )
        }
    }

    /**
     * Stops and closes the active `io.nekohasekai.libbox.BoxService` instance idempotently.
     */
    @Synchronized
    fun stopNativeBoxService() {
        val instance = activeBoxServiceInstance ?: return
        activeBoxServiceInstance = null
        runCatching {
            val closeMethod = instance.javaClass.methods.firstOrNull {
                it.name == "close" || it.name == "stop"
            }
            closeMethod?.invoke(instance)
        }
    }

    private fun createPlatformInvocationHandler(
        callbacks: NexoraTunPlatformCallbacks
    ): InvocationHandler {
        return InvocationHandler { _, method, args ->
            when (method.name) {
                "usePlatformAutoDetectInterfaceControl" -> true
                "autoDetectInterfaceControl" -> {
                    val fd = (args?.firstOrNull() as? Number)?.toInt() ?: -1
                    if (fd >= 0) {
                        val protected = callbacks.protectSocketFd(fd)
                        if (!protected) {
                            throw IllegalStateException("VpnService.protect(fd=$fd) returned false")
                        }
                    }
                    Unit
                }
                "openTun" -> {
                    val tunOptions = args?.firstOrNull()
                    val mtu = extractIntOption(tunOptions, "getMTU", 1500)
                    callbacks.openTunInterface(
                        mtu = mtu,
                        ipv4Address = "172.19.0.1",
                        ipv4Prefix = 30,
                        dnsAddress = "1.1.1.1"
                    )
                }
                "writeLog" -> {
                    val msg = args?.firstOrNull() as? String ?: ""
                    callbacks.onNativeCoreLog(LogRedactor.redact(msg))
                    Unit
                }
                "useProcFS" -> false
                "findConnectionOwner" -> -1
                "packageNameByUid" -> ""
                "uIDByPackageName" -> -1
                "localDNSTransport" -> null
                "hashCode" -> System.identityHashCode(this)
                "equals" -> false
                "toString" -> "NexoraLibboxPlatformInterface"
                else -> defaultValueForReturnType(method.returnType)
            }
        }
    }

    private fun extractIntOption(target: Any?, getterName: String, fallback: Int): Int {
        if (target == null) return fallback
        return try {
            val m = target.javaClass.methods.firstOrNull { it.name.equals(getterName, ignoreCase = true) }
            (m?.invoke(target) as? Number)?.toInt() ?: fallback
        } catch (_: Throwable) {
            fallback
        }
    }

    private fun defaultValueForReturnType(returnType: Class<*>): Any? {
        return when (returnType) {
            Boolean::class.javaPrimitiveType -> false
            Int::class.javaPrimitiveType -> 0
            Long::class.javaPrimitiveType -> 0L
            Float::class.javaPrimitiveType -> 0f
            Double::class.javaPrimitiveType -> 0.0
            String::class.java -> ""
            else -> null
        }
    }
}
